#!/usr/bin/env python3
"""Generate Markdown twins of the public pages into /md.

Run from the repo root:  python3 tools/build_markdown.py
Requires: beautifulsoup4, markdownify
The Cloudflare Worker in /worker serves these files when an agent sends
`Accept: text/markdown` (see worker/agent-edge.js).
"""
import re, sys
from pathlib import Path
from urllib.parse import urljoin
from bs4 import BeautifulSoup
from markdownify import markdownify as md

ROOT = Path(__file__).resolve().parent.parent
BASE = "https://bucharest365.vip/"
PAGES = {
    "index.html": "index", "bachelor.html": "bachelor", "limos.html": "limos", "vip.html": "vip",
    "nightlife.html": "nightlife", "restaurants.html": "restaurants", "tips365.html": "tips365",
    "faq.html": "faq", "privacy.html": "privacy", "terms.html": "terms", "accessibility.html": "accessibility",
}
DROP = ["script", "style", "noscript", "svg", "button", "form", "header", "footer", "nav", "iframe"]
DROP_SEL = ["#bachelor-popup", ".bachelor-popup-overlay", ".cookie-banner", ".skip-link", ".promo-bar", ".corner-logo", ".seo-topics"]


def convert(name: str) -> str:
    html = (ROOT / name).read_text(encoding="utf-8")
    soup = BeautifulSoup(html, "html.parser")
    title = soup.title.get_text(strip=True) if soup.title else name
    desc = soup.find("meta", attrs={"name": "description"})
    desc = desc["content"].strip() if desc and desc.get("content") else ""
    for sel in DROP_SEL:
        for el in soup.select(sel):
            el.decompose()
    for tag in DROP:
        for el in soup.find_all(tag):
            el.decompose()
    for row in soup.select(".rest-price-row"):
        spans, strongs = row.find_all("span"), row.find_all("strong")
        label = spans[0].get_text(" ", strip=True) if spans else ""
        value = strongs[0].get_text(" ", strip=True) if strongs else ""
        p = soup.new_tag("p")
        p.string = f"{label}: {value}" if label and value else (label or value)
        row.replace_with(p)
    for box in soup.select(".pkg-price"):
        p = soup.new_tag("p")
        p.string = box.get_text(" ", strip=True)
        box.replace_with(p)
    for a in soup.find_all("a", href=True):
        a["href"] = urljoin(BASE + name, a["href"])
    for img in soup.find_all("img"):
        img.decompose()
    body = soup.body or soup
    text = md(str(body), heading_style="ATX", bullets="-")
    text = re.sub(r"\n{3,}", "\n\n", text).strip()
    url = BASE if name == "index.html" else BASE + name
    head = f"<!-- Markdown version of {url} - generated by tools/build_markdown.py -->\n"
    if not re.search(r"^# ", text, re.M):
        head += f"# {title}\n\n"
    if desc:
        head += f"> {desc}\n\n"
    tail = f"\n\n---\nSource: {url}\nAgent guide: {BASE}llms.txt\nSitemap: {BASE}sitemap.xml\n"
    return head + text + tail


def main() -> int:
    out = ROOT / "md"
    out.mkdir(exist_ok=True)
    for name, slug in PAGES.items():
        (out / f"{slug}.md").write_text(convert(name), encoding="utf-8")
        print("wrote", f"md/{slug}.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
